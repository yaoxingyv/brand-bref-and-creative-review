# -*- coding: utf-8 -*-
"""向量库抽象接口。生产换 pgvector 时实现同一组方法即可替换 FAISS。"""

from typing import List, Protocol, Tuple


class VectorStore(Protocol):
    dim: int

    def add(self, vectors: List[List[float]], payloads: List[dict]) -> None: ...
    def search(self, query_vec: List[float], topk: int) -> List[Tuple[int, float]]: ...
    def payload(self, idx: int) -> dict: ...
    def clear(self) -> None: ...
    def save(self) -> None: ...
    def load(self) -> bool: ...
    def size(self) -> int: ...


__all__ = ["VectorStore"]
